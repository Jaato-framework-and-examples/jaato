def test_two_workspaces_one_daemon_no_bounce(tmp_path: Path) -> None:
    """Two clients, two workspaces, one daemon — both succeed, cross-
    workspace cli reads are kernel-denied.

    This is the ${prompt}'s §2.6 IS THE GATE test.  Implemented
    against the IPCClient SDK so the wire path is identical to a real
    TUI session.

    The test is intentionally written so each step explains itself in
    a failure message — when this test fires red, the assertion
    explains exactly which step regressed.
    """
    asyncio.run(_drive_two_workspaces(tmp_path))


async def _drive_two_workspaces(tmp_path: Path) -> None:
    """The body of the gate above, as a coroutine.

    Separated because ``IPCClient`` is an ASYNC client and this test
    drove it as a synchronous one -- ``connect(workspace=..., apparmor=
    ...)``, ``session_new``, ``wait_for_idle`` and ``get_history`` are
    all spellings that no longer exist anywhere in the SDK.  The first
    of them to be reached raised, so this gate had rotted through and
    through while reading as green (#736).

    THE REASON IT ROTTED UNSEEN IS THE ISSUE'S OWN THESIS, one level in.
    ``jaato-server/tests/`` was measured as green-and-wire-ready on two
    separate hosts, and both were hosts WITHOUT AppArmor -- where the
    module-level ``skipif`` above makes this file skip, and a skip is
    indistinguishable from a pass in a summary line.  CI has AppArmor,
    so the first commit-triggered run that actually reached this body
    found it broken.  "Green" measured in the wrong environment is not
    green, and this gate is the proof.

    Driven through the same idiom the live-conformance suite uses
    (``jaato_sdk/conformance/test_invariants.py``), which is the one
    daemon-driving pattern in this tree a commit-triggered workflow
    exercises -- so it cannot drift again without that suite going red
    too.
    """
    from jaato_sdk import IPCClient
    from jaato_sdk.events import ClientType

    ws_a = tmp_path / "ws_a"
    ws_b = tmp_path / "ws_b"
    ws_a.mkdir()
    ws_b.mkdir()
    _provision_workspace(ws_a)
    _provision_workspace(ws_b)

    sock = tmp_path / "jaato.sock"
    daemon_log = tmp_path / "daemon.log"
    daemon = _start_daemon(sock, daemon_log)

    client_a = client_b = None
    try:
        # ----- Client A: workspace_a session -----
        client_a = await _connect(
            IPCClient, ClientType, sock, ws_a,
        )
        sid_a = await client_a.create_session(profile="cli_test")
        assert sid_a, "session.new for client A returned no session_id"
        # #1253: the session's FIRST runner wears its profile from the
        # start, read from the kernel before any turn has run -- not the
        # runner a later turn or a revive gets.
        _assert_runner_wears_its_profile(
            await _runner_identity(client_a, sid_a))

        # Write a workspace-A file via cli — exercises the runner.
        await _drive_turn(
            client_a,
            f"create file via cli: echo hi-from-A > {ws_a}/sandbox/x",
        )
        assert (ws_a / "sandbox" / "x").exists(), (
            "session A's cli call did not create sandbox/x; the runner "
            "may have spawned but the cli RPC stub may not be wired"
        )

        # ----- Client B: the 7:3 regression case -----
        # NO daemon bounce between A and B.  This is the load-bearing
        # assertion: pre-Phase-2, the daemon's apparmor profile was
        # pinned to A's workspace and B's session.new failed at the
        # IPC handshake.
        client_b = await _connect(
            IPCClient, ClientType, sock, ws_b,
        )
        sid_b = await client_b.create_session(profile="cli_test")
        assert sid_b, (
            "session.new for client B returned no session_id — "
            "this is the 7:3 regression case (cross-workspace IPC "
            "handshake failed)"
        )

        await _drive_turn(
            client_b,
            f"create file via cli: echo hi-from-B > {ws_b}/sandbox/y",
        )
        assert (ws_b / "sandbox" / "y").exists()

        # ----- Which profile each runner wears -----
        # Profiles are named after the BOUNDARY (workspace + rendered
        # body), not the session (#1033 / #1037): ``jaato-ws-<slug>-
        # <digest>``.  Read the name the daemon recorded for each runner
        # (#812's runner identity, on the ``session.list`` rows) rather
        # than reconstructing it.
        profile_a = await _runner_profile(client_a, sid_a)
        profile_b = await _runner_profile(client_b, sid_b)
        assert profile_a and profile_b and profile_a != profile_b, (
            f"two workspaces must be two AppArmor boundaries; got "
            f"A={profile_a!r} B={profile_b!r}"
        )

        # ----- Cross-workspace read MUST be kernel-denied -----
        # Wrapped in ``sh -c`` on purpose: a bare ``cat <path>`` outside
        # the workspace is refused by cli's own path check before
        # anything runs, which proves the string layer and leaves the
        # kernel untouched.  The analyzer does not descend into the
        # quoted argument of ``sh -c``, so this read reaches the
        # ``//child`` profile and is the kernel's to deny.
        await _drive_turn(
            client_b,
            f"run exactly this with the cli tool, unchanged: "
            f"sh -c 'cat {ws_a}/sandbox/x'",
        )
        # The cli result on B should report Permission denied.  There is
        # no structured-result accessor on the SDK, so pull the session's
        # history and walk it for the last cli payload.
        history = await _history(client_b)
        _assert_cross_read_denied(_last_cli_result(history))
        _assert_kernel_denial(profile_b, ws_a / "sandbox" / "x")
    except BaseException:
        # The daemon's stdout/stderr is the only account of WHY a step
        # failed, and until now this test wrote it to ``tmp_path`` and
        # never read it -- so the first CI run to reach this body
        # reported ``SessionNotConfirmed: session.new was sent but not
        # answered within 60.0s`` and nothing about the refusal the
        # daemon had already logged.  That is the #882 shape seen from
        # the client side: a refused ``session.new`` is logged and never
        # answered, so the caller learns only that it waited.
        #
        # Printed rather than raised-with: pytest captures stdout and
        # shows it on failure, and a teardown that itself raises must not
        # be able to replace the original exception.
        _print_daemon_log(daemon_log)
        raise
    finally:
        for client in (client_a, client_b):
            if client is not None:
                try:
                    await client.disconnect()
                except Exception:       # noqa: BLE001 - teardown only
                    pass
        _stop_daemon(daemon)


