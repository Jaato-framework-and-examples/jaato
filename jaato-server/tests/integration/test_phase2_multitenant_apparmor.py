"""§2.6 / §8.2 acceptance gate — the 7:3 regression test.

Two clients in two different workspaces opt into AppArmor against a
single daemon.  Both must succeed end-to-end without a daemon bounce
between them, and a cli call from session-B must NOT be able to read
session-A's workspace files (kernel-enforced via the per-session
runner's AppArmor profile).

This test is the load-bearing acceptance gate for Phase 2.  Per
operator direction (plan §6.8), it runs on a user-hosted server with
CAP_MAC_ADMIN + CAP_SYSLOG; CI without those caps skips cleanly via
the ``apparmor`` mark + ``apparmor_available()`` skipif.

The test is structured as a scaffold:
- Helpers + fixture for spawning + tearing down a daemon subprocess.
- Profile-fixture writer producing the YAML profile shape from plan §4.
- The actual driving logic uses the ``IPCClient`` from jaato-sdk.

Phase 2 ships this test with a skipif that auto-skips on hosts
without AppArmor, so it's safe to commit.  The user-hosted runner
will exercise it for real.
"""

from __future__ import annotations

import asyncio
import os
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

import pytest

from ._apparmor_helpers import (
    SKIP_REASON_NO_APPARMOR,
    apparmor_available,
    dmesg_available,
)


pytestmark = [
    pytest.mark.apparmor,
    pytest.mark.skipif(not apparmor_available(), reason=SKIP_REASON_NO_APPARMOR),
]


