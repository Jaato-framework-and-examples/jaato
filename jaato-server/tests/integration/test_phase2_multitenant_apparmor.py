def _print_daemon_log(log_path: Path, tail_lines: int = 120) -> None:
    """Emit the daemon's own account of a failed step.

    This test spawns the daemon itself and sends its stdout+stderr to
    ``tmp_path/daemon.log``.  That file was written and never read: on
    the first commit-triggered run that actually reached this body, the
    failure surfaced as a bare 60 s ``SessionNotConfirmed`` while the
    reason sat on disk, and ``tmp_path`` was then cleaned away.

    Tail rather than whole: bootstrap chatter dominates the head, and
    the answer to "why did this step fail" is always at the end.
    Best-effort by construction -- a diagnostic that can itself raise
    would replace the exception it exists to explain.
    """
    try:
        text = log_path.read_text(errors="replace")
    except OSError as exc:              # noqa: BLE001 - diagnostic only
        print(f"\n--- daemon log at {log_path} unreadable: {exc} ---")
        return

    lines = text.splitlines()
    shown = lines[-tail_lines:]
    elided = len(lines) - len(shown)
    print(f"\n--- daemon log ({log_path}), last {len(shown)} of "
          f"{len(lines)} lines ---")
    if elided > 0:
        print(f"    [{elided} earlier lines elided]")
    for line in shown:
        print(f"    {line}")
    print("--- end daemon log ---\n")



def _assert_cross_read_denied(last_result: Optional[dict]) -> None:
    """The cross-workspace read failed, and it was not cli's string
    check that stopped it (that would leave the kernel unexercised)."""
    assert last_result is not None, (
        "expected a cli tool result in B's history after the "
        "cross-workspace read attempt"
    )
    assert "cli containment" not in (last_result.get("error") or ""), (
        "cli's string-level path check refused the read before it "
        "ran, so the kernel boundary was never exercised: "
        f"{last_result!r}"
    )
    # Either the cli returns a non-zero exit (cat: ENOENT
    # because apparmor masks the path as not-found) OR the
    # result.error mentions Permission denied.  Both are
    # legitimate apparmor-enforced outcomes.
    assert (
        "Permission denied" in (last_result.get("stderr") or "")
        or "Permission denied" in (last_result.get("error") or "")
        or last_result.get("returncode", 0) != 0
    ), (
        f"expected cross-workspace cat to fail but got {last_result!r}"
    )


def _assert_kernel_denial(profile: str, path: Path) -> None:
    """dmesg carries a DENIED line for *profile* on *path*.

    ONE audit line must carry all three facts: a denial, the profile
    (``//child`` included, hence the open quote), and the file.
    ``tmp_path`` is unique per run, so the name alone scopes the match
    to this test.  The old check looked for ``profile="jaato-ws-<session
    id>`` -- a name no profile has carried since #1033 -- and for
    "DENIED" anywhere in the ring buffer.
    """
    if not dmesg_available():
        print(
            "dmesg unavailable — skipping kernel-audit assertion. "
            "Userspace assertions still cover the deny."
        )
        return
    dmesg = subprocess.check_output(["dmesg", "-T"]).decode(errors="replace")
    target = f'name="{path}"'
    denials = [
        line for line in dmesg.splitlines()
        if 'apparmor="DENIED"' in line
        and f'profile="{profile}' in line
        and target in line
    ]
    assert denials, (
        f"expected a DENIED apparmor audit line for profile {profile} "
        f"on {path}; none found"
    )


async def _connect(ipc_client_cls, client_type_enum, sock: Path, ws: Path):
    """Connect one AppArmor-confined client to the shared daemon.

    ``workspace_path`` and ``apparmor`` are CONSTRUCTOR arguments; this
    test used to pass them to ``connect()``, which takes only a timeout.
    ``client_type`` is required (keyword-only) and is what the CI run
    tripped over first.  ``auto_start=False`` because the daemon in this
    test is spawned by hand and shared by both clients — the whole point
    of the gate is that there is NO bounce between A and B.
    """
    client = ipc_client_cls(
        socket_path=str(sock),
        client_type=client_type_enum.API,
        workspace_path=str(ws),
        apparmor=True,
        auto_start=False,
    )
    assert await client.connect(timeout=60), (
        f"could not connect to the test daemon at {sock} for workspace {ws}"
    )
    return client


async def _drive_turn(client, prompt: str, timeout: float = 60.0) -> None:
    """Send one prompt and wait for the turn to complete.

    Replaces the ``send_message`` + ``wait_for_idle`` pair this test used
    to call; neither exists on the async client.  The collector is armed
    BEFORE the send, as in the conformance suite, or a fast turn can
    complete before anything is listening and the wait hangs to its
    timeout.
    """
    from jaato_sdk.events import TurnCompletedEvent

    async def collect():
        async for ev in client.events():
            if isinstance(ev, TurnCompletedEvent):
                return

    task = asyncio.create_task(collect())
    await asyncio.sleep(0.2)
    await client.send_message(prompt)
    try:
        await asyncio.wait_for(task, timeout=timeout)
    except asyncio.TimeoutError:
        task.cancel()
        raise AssertionError(
            f"no TurnCompletedEvent within {timeout}s for prompt {prompt!r}"
        )


async def _runner_profile(client, session_id: str,
                          timeout: float = 30.0) -> str:
    """The AppArmor profile the daemon recorded for a session's runner.

    ``session.list`` rows carry ``runner`` -- the #812 runner identity,
    whose ``apparmor_profile`` is the profile the runner was spawned
    into.  An empty value means the session is NOT confined, which this
    gate treats as a failure: everything after it would be measuring an
    unconfined runner.
    """
    identity = await _runner_identity(client, session_id, timeout)
    profile = identity.get("apparmor_profile") or ""
    assert profile.startswith("jaato-ws-"), (
        f"session {session_id}'s runner is not AppArmor-confined "
        f"(runner identity: {identity!r})"
    )
    return profile


def _assert_runner_wears_its_profile(identity: dict) -> None:
    """Every thread of the runner wears its recorded profile, enforced (#1253).

    #1100 / #1253: a session's first runner (a pool slot) spawned before
    the profile was provisioned and served the session unconfined while
    the daemon recorded ``apparmor``.  The daemon now refuses a session
    whose runner does not report the profile; this reads the KERNEL's
    answer for the process the daemon named, so a run on an enforcing
    host checks the fix rather than the daemon's account of it.
    """
    pid = identity.get("runner_pid")
    profile = identity.get("apparmor_profile") or ""
    assert pid and profile.startswith("jaato-ws-"), (
        f"no confined runner recorded: {identity!r}"
    )
    task_dir = Path(f"/proc/{pid}/task")
    labels = {}
    for task in sorted(task_dir.iterdir()):
        raw = (task / "attr" / "current").read_text(errors="replace")
        labels[task.name] = raw.replace("\x00", "").strip()
    # Through the one label parser (#1014 / #1509): a stack with
    # ``unconfined`` is its profile, the mode must be enforce.
    from jaato_server.shared.apparmor_label import parse_label
    wrong = {
        tid: label for tid, label in labels.items()
        if parse_label(label).profile != profile
        or not parse_label(label).enforced
    }
    assert not wrong, (
        f"runner pid={pid} should wear {profile!r} (enforce) on every "
        f"thread; these do not: {wrong!r}"
    )


async def _runner_identity(client, session_id: str,
                           timeout: float = 30.0) -> dict:
    """The #812 runner identity the daemon recorded for *session_id*."""
    from jaato_sdk.events import SessionListEvent

    async def collect():
        async for ev in client.events():
            if isinstance(ev, SessionListEvent):
                return list(ev.sessions)
        return []

    task = asyncio.create_task(collect())
    await asyncio.sleep(0.2)
    await client.list_sessions()
    try:
        rows = await asyncio.wait_for(task, timeout=timeout)
    except asyncio.TimeoutError:
        task.cancel()
        raise AssertionError(f"no SessionListEvent within {timeout}s")
    row = next((r for r in rows if r.get("id") == session_id), None)
    assert row is not None, f"session {session_id} not in session.list"
    return dict(row.get("runner") or {})


async def _history(client, timeout: float = 30.0) -> list:
    """Fetch the session's history.

    ``get_history()`` was a synchronous accessor and is gone: history is
    REQUESTED and arrives as a ``HistoryEvent`` on the event stream.
    """
    from jaato_sdk.events import HistoryEvent

    async def collect():
        async for ev in client.events():
            if isinstance(ev, HistoryEvent):
                return list(ev.history)
        return []

    task = asyncio.create_task(collect())
    await asyncio.sleep(0.2)
    await client.request_history()
    try:
        return await asyncio.wait_for(task, timeout=timeout)
    except asyncio.TimeoutError:
        task.cancel()
        raise AssertionError(f"no HistoryEvent within {timeout}s")


def _last_cli_result(history) -> Optional[dict]:
    """Walk a session's history backwards looking for the last cli
    tool result.  Returns the result dict (the structured payload the
    daemon-side stub forwarded) or ``None`` if nothing matched.

    ``HistoryEvent.history`` carries SERIALIZED ``Message`` dicts --
    ``{role, parts: [{type: 'function_response', call_id, name, result},
    ...]}`` -- so the payload sits one level down, inside a part, and a
    walk over the top level alone finds nothing.  The flat shapes are
    still accepted first: this helper predates the async history path
    and a tolerant match costs nothing.
    """
    if not history:
        return None
    items = list(history) if not isinstance(history, list) else history

    def _payload(candidate) -> Optional[dict]:
        if not isinstance(candidate, dict):
            return None
        if "stdout" in candidate or "returncode" in candidate:
            return candidate
        inner = candidate.get("result") or candidate.get("tool_result")
        if isinstance(inner, dict) and (
            "stdout" in inner or "returncode" in inner
        ):
            return inner
        return None

    for item in reversed(items):
        hit = _payload(item)
        if hit is not None:
            return hit
        # Descend into a serialized Message's parts.
        if isinstance(item, dict):
            for part in reversed(item.get("parts") or []):
                hit = _payload(part)
                if hit is not None:
                    return hit
    return None
